CREATE TABLE laboratories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    inscricao_fiscal VARCHAR(255) NOT NULL UNIQUE,
    logradouro VARCHAR(255) NOT NULL,
    cidade VARCHAR(255) NOT NULL,
    estado VARCHAR(255) NOT NULL,
    cep VARCHAR(255) NOT NULL
);

CREATE TABLE properties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    inscricao_fiscal VARCHAR(255) NOT NULL UNIQUE,
    logradouro VARCHAR(255) NOT NULL,
    cidade VARCHAR(255) NOT NULL,
    estado VARCHAR(255) NOT NULL,
    cep VARCHAR(255) NOT NULL
);

CREATE TABLE producers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    inscricao_fiscal VARCHAR(255) NOT NULL UNIQUE,
    logradouro VARCHAR(255) NOT NULL,
    cidade VARCHAR(255) NOT NULL,
    estado VARCHAR(255) NOT NULL,
    cep VARCHAR(255) NOT NULL,
    laboratory_id BIGINT NOT NULL,
    data_inicial TIMESTAMP,
    data_final TIMESTAMP,
    observacoes TEXT,
    CONSTRAINT fk_producer_laboratory FOREIGN KEY (laboratory_id) REFERENCES laboratories(id)
);

CREATE TABLE producer_properties (
    producer_id BIGINT NOT NULL,
    property_id BIGINT NOT NULL,
    PRIMARY KEY (producer_id, property_id),
    CONSTRAINT fk_producer_properties_producer FOREIGN KEY (producer_id) REFERENCES producers(id),
    CONSTRAINT fk_producer_properties_property FOREIGN KEY (property_id) REFERENCES properties(id)
);

CREATE TABLE sync_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(255) NOT NULL,
    external_reference VARCHAR(255) NOT NULL,
    status VARCHAR(50) NOT NULL,
    payload TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    error_message TEXT,
    attempt_count INTEGER NOT NULL DEFAULT 0
);
